#!/usr/bin/env python3
"""Generate an EAGLE (XML, v7 format) schematic from Civic-Workbench's reviewed netlist.

The .sch file is self-contained (embedded library: symbols, packages, devices) and is meant
for Proteus "Import EAGLE" (newer Proteus 8 releases) or any EAGLE-compatible tool (KiCad).
Connectivity uses pin stubs + net labels; same-named nets are electrically joined.

Usage:  python3 tools/generate_eagle_schematic.py [--output path/to/file.sch]
"""
from __future__ import annotations

import argparse
from pathlib import Path
import xml.etree.ElementTree as ET
import yaml

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "hardware/reference/esp32-tja1051-netlist.yaml"
DEFAULT_OUTPUT = ROOT / "hardware/proteus/generated/civic-workbench-rev-b.sch"
G = 2.54  # 0.1 inch grid, mm

LAYERS = [(1, "Top"), (16, "Bottom"), (17, "Pads"), (18, "Vias"), (19, "Unrouted"), (20, "Dimension"),
          (21, "tPlace"), (25, "tNames"), (27, "tValues"), (29, "tStop"), (31, "tCream"), (51, "tDocu"),
          (91, "Nets"), (92, "Busses"), (93, "Pins"), (94, "Symbols"), (95, "Names"), (96, "Values"),
          (97, "Info"), (98, "Guide")]

# ---------------------------------------------------------------- library definitions
# Each symbol: pins as (name, x, y, rot); rot R0 = pin to the left of body pointing right, etc.
# Stub direction for net labels follows from rot: R0 -> -x, R180 -> +x, R270 -> +y, R90 -> -y.
STUB = {"R0": (-1, 0), "R180": (1, 0), "R270": (0, 1), "R90": (0, -1)}


def tja1051_symbol():
    left = [("TXD", 1), ("GND", 2), ("VCC", 3), ("RXD", 4)]
    right = [("S", 8), ("CANH", 7), ("CANL", 6), ("NC", 5)]
    pins = [(n, -6 * G, (1.5 - i) * 2 * G, "R0") for i, (n, _) in enumerate(left)]
    pins += [(n, 6 * G, (1.5 - i) * 2 * G, "R180") for i, (n, _) in enumerate(right)]
    body = (-4 * G, -4.5 * G, 4 * G, 4.5 * G)
    pads = {n: str(p) for n, p in left + right}
    return {"pins": pins, "body": body, "pads": pads, "pin_length": "short"}


def two_pin_symbol(kind):
    return {"pins": [("1", 0, 3 * G, "R270"), ("2", 0, -3 * G, "R90")],
            "body": (-G * 0.4, -2 * G, G * 0.4, 2 * G) if kind == "R" else None,
            "pads": {"1": "1", "2": "2"}, "pin_length": "short", "kind": kind}


def header_symbol(names):
    n = len(names)
    pins = [(name, -4 * G, ((n - 1) / 2 - i) * 2 * G, "R0") for i, name in enumerate(names)]
    return {"pins": pins, "body": (-2 * G, -n * G, 2 * G, n * G), "pin_length": "short"}


def build_library(design):
    lib = {}
    lib["TJA1051"] = {**tja1051_symbol(), "package": "SO8", "prefix": "U"}
    lib["R"] = {**two_pin_symbol("R"), "package": "R0805", "prefix": "R"}
    lib["C"] = {**two_pin_symbol("C"), "package": "C0805", "prefix": "C"}
    for comp in design["components"]:
        if comp["ref"].startswith("J"):
            names = [str(p) for p in comp["nets"]]
            sym = header_symbol(names)
            sym.update(pads={n: n for n in names}, package=f"HDR{len(names)}", prefix="J")
            lib[f"HDR{len(names)}"] = sym
    conns = design["controller"]["connections"]
    mcu = header_symbol([c["pin"] for c in conns])
    mcu["pins"] = [(n, x + 8 * G, y, "R180") for n, x, y, _ in mcu["pins"]]
    mcu.update(pads={c["pin"]: str(c["header_pin"]) for c in conns}, package="NODEMCU32S_HDR", prefix="J",
               body=(-4 * G, -3 * G, 4 * G, 3 * G))
    lib["NODEMCU32S"] = mcu
    return lib


def deviceset_for(ref, comp):
    if ref == "U1":
        return "TJA1051"
    if ref.startswith("R"):
        return "R"
    if ref.startswith("C"):
        return "C"
    return f"HDR{len(comp['nets'])}"


def sub(parent, tag, **attrs):
    return ET.SubElement(parent, tag, {k: (f"{v:.4f}".rstrip("0").rstrip(".") if isinstance(v, float) else str(v))
                                        for k, v in attrs.items()})


def add_library(libraries, lib):
    library = sub(libraries, "library", name="civic_workbench")
    sub(library, "description").text = "Generated by tools/generate_eagle_schematic.py"
    packages = sub(library, "packages")
    for name, sym in lib.items():
        pkg = sub(packages, "package", name=sym["package"])
        pads = list(dict.fromkeys(sym["pads"].values()))
        for i, pad in enumerate(pads):
            if sym["package"] in ("SO8",):
                n = int(pad)
                x = (-2.7 if n <= 4 else 2.7)
                y = (1.905 - (n - 1) * 1.27) if n <= 4 else (-1.905 + (n - 5) * 1.27)
                sub(pkg, "smd", name=pad, x=x, y=y, dx=1.5, dy=0.6, layer=1)
            elif sym["package"] in ("R0805", "C0805"):
                sub(pkg, "smd", name=pad, x=(-0.95 if i == 0 else 0.95), y=0, dx=1.0, dy=1.3, layer=1)
            else:
                sub(pkg, "pad", name=pad, x=0, y=-i * G, drill=1.0)
        sub(pkg, "text", x=0, y=3, size=1.27, layer=25).text = ">NAME"
    symbols = sub(library, "symbols")
    for name, sym in lib.items():
        s = sub(symbols, "symbol", name=name)
        if sym.get("kind") == "C":
            sub(s, "wire", x1=-1.6, y1=0.5, x2=1.6, y2=0.5, width=0.4, layer=94)
            sub(s, "wire", x1=-1.6, y1=-0.5, x2=1.6, y2=-0.5, width=0.4, layer=94)
            sub(s, "wire", x1=0, y1=0.5, x2=0, y2=G * 3 - G, width=0.15, layer=94)
            sub(s, "wire", x1=0, y1=-0.5, x2=0, y2=-G * 3 + G, width=0.15, layer=94)
        elif sym.get("body"):
            x1, y1, x2, y2 = sym["body"]
            for a, b, c, d in ((x1, y1, x2, y1), (x2, y1, x2, y2), (x2, y2, x1, y2), (x1, y2, x1, y1)):
                sub(s, "wire", x1=a, y1=b, x2=c, y2=d, width=0.254, layer=94)
        if sym.get("kind") in ("R", "C"):
            name_xy, value_xy = (2 * G * 0.6, 0.5 * G), (2 * G * 0.6, -0.5 * G)
        else:
            bx1, by1, bx2, by2 = sym["body"]
            name_xy, value_xy = (bx1, by2 + 0.5 * G), (bx1, by1 - 1.2 * G)
        sub(s, "text", x=name_xy[0], y=name_xy[1], size=1.778, layer=95).text = ">NAME"
        sub(s, "text", x=value_xy[0], y=value_xy[1], size=1.778, layer=96).text = ">VALUE"
        vis = "pin" if name in ("TJA1051", "NODEMCU32S") or name.startswith("HDR") else "off"
        for pname, x, y, rot in sym["pins"]:
            sub(s, "pin", name=pname, x=x, y=y, length=sym["pin_length"], rot=rot, visible=vis)
    devicesets = sub(library, "devicesets")
    for name, sym in lib.items():
        ds = sub(devicesets, "deviceset", name=name, prefix=sym["prefix"], uservalue="yes")
        sub(sub(ds, "gates"), "gate", name="G$1", symbol=name, x=0, y=0)
        dev = sub(sub(ds, "devices"), "device", name="", package=sym["package"])
        connects = sub(dev, "connects")
        for pname, *_ in sym["pins"]:
            sub(connects, "connect", gate="G$1", pin=pname, pad=sym["pads"][pname])
        sub(sub(dev, "technologies"), "technology", name="")


def build(design) -> ET.ElementTree:
    lib = build_library(design)
    eagle = ET.Element("eagle", version="7.7.0")
    drawing = sub(eagle, "drawing")
    sub(sub(drawing, "settings"), "setting", alwaysvectorfont="no")
    sub(drawing, "grid", distance=0.1, unitdist="inch", unit="inch", style="lines", multiple=1,
        display="no", altdistance=0.01, altunitdist="inch", altunit="inch")
    layers = sub(drawing, "layers")
    for num, name in LAYERS:
        sub(layers, "layer", number=num, name=name, color=7, fill=1, visible="yes", active="yes")
    sch = sub(drawing, "schematic")
    add_library(sub(sch, "libraries"), lib)
    sub(sch, "attributes"); sub(sch, "variantdefs")
    sub(sub(sch, "classes"), "class", number=0, name="default", width=0, drill=0)

    # placement (mm, on 0.1" grid)
    place = {"J1": (20 * G, 40 * G), "U1": (55 * G, 40 * G),
             "R1": (85 * G, 48 * G), "R2": (95 * G, 48 * G), "C1": (105 * G, 48 * G),
             "R3": (85 * G, 28 * G), "R4": (95 * G, 28 * G), "C2": (105 * G, 28 * G),
             "J2": (20 * G, 15 * G), "J3": (45 * G, 15 * G),
             "R5": (70 * G, 10 * G), "R6": (80 * G, 10 * G), "C5": (90 * G, 10 * G),
             "C3": (100 * G, 10 * G), "C4": (110 * G, 10 * G)}

    parts = sub(sch, "parts")
    sheet = sub(sub(sch, "sheets"), "sheet")
    plain = sub(sheet, "plain")
    sub(plain, "text", x=10 * G, y=60 * G, size=3.81, layer=97).text = \
        f"Civic-Workbench Rev {design['revision']} - NodeMCU-32S + NXP TJA1051T receive-only CAN"
    notes = ["U1 S pulled to +5V_CAN (Silent). GPIO21 not wired: Rev B cannot transmit.",
             "RXD -> R3/R4 divider -> GPIO22 (<= 3.44 V). U1 pin 5 open (fail-safe).",
             "R5, R6, C3, C4, C5 = DNP: fit only per bench bus topology. Never terminate onto a vehicle bus.",
             "Generated from hardware/reference/esp32-tja1051-netlist.yaml - do not edit by hand."]
    for i, n in enumerate(notes):
        sub(plain, "text", x=10 * G, y=(57 - 2 * i) * G, size=1.778, layer=97).text = n
    instances = sub(sheet, "instances")
    sub(sheet, "busses")
    nets_el = sub(sheet, "nets")

    pin_nets: dict[str, list[tuple[str, str]]] = {}
    sym_of: dict[str, dict] = {}

    conns = design["controller"]["connections"]
    sub(parts, "part", name="J1", library="civic_workbench", deviceset="NODEMCU32S", device="", value="NodeMCU-32S")
    sym_of["J1"] = lib["NODEMCU32S"]
    for c in conns:
        if not c["net"].startswith("NC_"):
            pin_nets.setdefault(c["net"], []).append(("J1", c["pin"]))

    for comp in design["components"]:
        ref = comp["ref"]
        ds = deviceset_for(ref, comp)
        value = comp["value"] if comp["fitted"] else f"DNP {comp['value']}"
        sub(parts, "part", name=ref, library="civic_workbench", deviceset=ds, device="", value=value)
        sym_of[ref] = lib[ds]
        names = [p[0] for p in lib[ds]["pins"]]
        for pin, net in comp["nets"].items():
            net = str(net)
            if net.startswith("NC_"):
                continue
            if ref == "U1":
                pin_name = {v: k for k, v in lib["TJA1051"]["pads"].items()}[str(pin)]
            else:
                pin_name = str(pin)
            assert pin_name in names, (ref, pin_name)
            pin_nets.setdefault(net, []).append((ref, pin_name))

    for ref, (x, y) in place.items():
        if ref in sym_of:
            sub(instances, "instance", part=ref, gate="G$1", x=x, y=y)

    for net in sorted(pin_nets):
        n_el = sub(nets_el, "net", name=net, **{"class": 0})
        for ref, pin_name in sorted(pin_nets[net]):
            px0, py0 = place[ref]
            _, sx, sy, rot = next(p for p in sym_of[ref]["pins"] if p[0] == pin_name)
            px, py = px0 + sx, py0 + sy
            dx, dy = STUB[rot]
            ex, ey = px + dx * 2 * G, py + dy * 2 * G
            seg = sub(n_el, "segment")
            sub(seg, "pinref", part=ref, gate="G$1", pin=pin_name)
            sub(seg, "wire", x1=px, y1=py, x2=ex, y2=ey, width=0.1524, layer=91)
            label_rot = "R180" if dx < 0 else ("R90" if dy > 0 else ("R270" if dy < 0 else "R0"))
            sub(seg, "label", x=ex, y=ey, size=1.778, layer=95, rot=label_rot, xref="yes")
    ET.indent(eagle, space="  ")
    return ET.ElementTree(eagle)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    design = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))
    tree = build(design)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("wb") as stream:
        stream.write(b'<?xml version="1.0" encoding="utf-8"?>\n<!DOCTYPE eagle SYSTEM "eagle.dtd">\n')
        tree.write(stream, encoding="utf-8", xml_declaration=False)
        stream.write(b"\n")
    print(args.output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
